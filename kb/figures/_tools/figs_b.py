# 9. 相邻零件剖面线方向
# ---------------------------------------------------------------------------
def fig_poumainxian() -> Figure:
    F = Figure(
        "FIG-POUMAINXIAN",
        960,
        560,
        "相邻零件剖面线方向应相反",
        "同一剖视图中两个相邻零件：一个剖面线画 45°、另一个画 135°，方向相反，使两个零件一眼可分。",
    )
    fig_title(
        F,
        "图 9  相邻零件的剖面线方向（剖视图中的装配画法）",
        "零件 1 为凹形块、零件 2 为凸块，两者装配在一起后同时被剖切。",
    )

    # 零件 1：凹形块，剖面线 45°
    d1 = "M200,150 L310,150 L310,230 L410,230 L410,150 L520,150 L520,290 L200,290 Z"
    F.hatch(d1, "hatch45")
    F.path(d1, cls="thick")
    # 零件 2：凸块，剖面线 135°
    F.hatch("M310,150 L410,150 L410,230 L310,230 Z", "hatch135")
    F.rect(310, 150, 100, 80, cls="thick")

    # 引注
    F.leader(214, 250, 150, 330, "零件 1：剖面线 45°", color=BLUE, anchor="start", size=11)
    F.leader(430, 166, 490, 116, "零件 2：剖面线 135°", color=RED, anchor="start", size=11)
    F.text(360, 322, "两零件的接触面画一条粗实线（不画两条）", size=11, color=MUTED)

    notes = [
        "① 同一零件在各剖视图中的剖面线方向、间距必须一致 —— 这样读图时才能把同一个零件认出来。",
        "② 相邻两个零件的剖面线方向应相反（本图 45° 与 135°）。",
        "③ 若不便反向，则方向可以相同，但间距必须不同，靠疏密区分两个零件。",
        "④ 剖面线用细实线，与主要轮廓线成 45°（也可 30° 或 60°），间距均匀（本图 6 px）。",
        "⑤ 相邻零件的接触面只画一条粗实线；非接触面（有间隙）各画各的轮廓线。",
    ]
    F.lines(40, 380, notes, size=11, lh=23)
    return F


