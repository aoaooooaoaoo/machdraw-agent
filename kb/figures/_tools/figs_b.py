# 8. 断面图 vs 剖视图 对照
# ---------------------------------------------------------------------------
def fig_duanmian() -> Figure:
    F = Figure(
        "FIG-DUANMIAN",
        1000,
        580,
        "断面图与剖视图的区别",
        "同一零件、同一剖切位置、同一投射方向：断面图只画断面形状，剖视图在断面形状之外"
        "还要画出剖切平面后方所有可见轮廓（如底板轮廓）。",
    )
    fig_title(
        F,
        "图 8  断面图与剖视图的区别（同一零件、同一剖切位置、同一投射方向）",
        "零件：Ø40 立柱 + 肋板 40×16，立在 100×100 底板上；沿立柱中部水平剖切，向下投射。",
    )

    def section_pts(cx: float, cy: float, r: float = 40.0, rib: float = 40.0, half: float = 8.0):
        """圆（Ø40）+ 向右伸出的肋板，合成一个封闭断面轮廓（点列）。

        圆弧从右上方的切出点 A 绕过左侧（336.9°）到右下方 B，再沿肋板折回。
        """
        a0 = -11.537  # = asin(-half / r)，A 点角度；B 点 = +11.537°
        pts = arc_pts(cx, cy, r, a0, a0 - 360 + 2 * abs(a0), 64)
        return pts + [(cx + r + rib, cy + half), (cx + r + rib, cy - half)]

    def d_of(pts) -> str:
        return "M" + " L".join(f"{x:.2f},{y:.2f}" for x, y in pts) + " Z"

    # ---------- 左：断面图 ----------
    d_l = d_of(section_pts(270, 300))
    F.hatch(d_l)
    F.path(d_l, cls="thick")
    F.text(270, 232, "断面图", size=13, weight="600")
    F.text(270, 250, "A—A", size=11, color=MUTED)
    F.text(270, 392, "只画剖切面与形体相交的断面形状", size=11)
    F.text(270, 410, "（肋板：断面照画剖面线）", size=11, color=MUTED)

    # ---------- 右：剖视图 ----------
    F.rect(600, 200, 200, 200, cls="thick")  # 底板轮廓：断面图里没有
    d_r = d_of(section_pts(700, 300))
    F.hatch(d_r)
    F.path(d_r, cls="thick")
    F.text(700, 172, "剖视图", size=13, weight="600")
    F.text(700, 190, "A—A", size=11, color=MUTED)
    F.text(700, 440, "断面形状 + 剖切面后方可见轮廓", size=11)
    F.text(700, 458, "（底板轮廓可见，但不画剖面线）", size=11, color=MUTED)

    # ---------- 差异注释 ----------
    F.leader(800, 250, 858, 220, "底板轮廓（断面图没有）", color=RED, anchor="start")
    F.leader(350, 300, 452, 336, "肋板（断面照画剖面线）", color=BLUE, anchor="start")

    notes = [
        "① 断面图只表达剖切面切断形体后得到的断面形状；剖视图还要把剖切面后方所有可见轮廓都画出来。",
        "② 断面图与剖视图的剖面线画法相同（45° 细实线）；但断面图中不会出现剖切面后方的轮廓线。",
        "③ 移出断面图一般画在视图之外，用剖切符号（粗短画 + 箭头 + 字母）标注；不对称的断面必须标箭头。",
        "④ 判断口诀：图里出现“后面看得到的轮廓”—— 是剖视图；“只有一个断面”—— 是断面图。",
    ]
    F.lines(40, 496, notes, size=11, lh=23)
    return F


