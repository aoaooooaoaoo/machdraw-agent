# 6. 半剖视图
# ---------------------------------------------------------------------------
def fig_poushi_ban() -> Figure:
    F = Figure(
        "FIG-POUSHI-BAN",
        1000,
        620,
        "半剖视图：以对称中心线为界，一半剖一半视图",
        "对称零件（法兰套筒 Ø80/Ø60、内孔 Ø24）以对称中心线为分界，左半画剖视、右半画视图；"
        "视图半侧不画虚线。",
    )
    fig_title(
        F,
        "图 6  半剖视图（对称零件：法兰 Ø80、筒体 Ø60、内孔 Ø24，高 50）",
        "半剖适用于对称零件 —— 一半表达内形、一半表达外形，一个视图兼顾两者。",
    )

    # 外形轮廓（两侧都画）
    F.path("M400,360 L560,360 L560,330 L540,330 L540,260 L420,260 L420,330 L400,330 Z", cls="thick")
    # 剖视侧（左半）：孔壁粗实线 + 剖面线
    F.line(456, 260, 456, 360, cls="thick")
    F.hatch_rect(420, 260, 36, 70)
    F.hatch_rect(400, 330, 56, 30)
    # 对称中心线 = 剖与不剖的分界
    F.line(480, 240, 480, 384, cls="center", color=MUTED)

    F.text(440, 246, "剖视（左半）", size=12, weight="600")
    F.text(524, 246, "视图（右半）", size=12, weight="600")
    F.text(480, 400, "对称中心线（分界）", size=11, color=MUTED)
    F.leader(456, 316, 336, 296, "Ø24 孔壁：粗实线", color=BLUE, anchor="end")

    # 尺寸
    F.dim_v(600, 260, 360, "50", ext_from=(540, 540), left=False)
    F.dim_h(400, 560, 424, "Ø80", ext_from=(360, 360), above=False)
    F.leader(544, 276, 636, 266, "Ø60", color=MUTED, anchor="start")

    notes = [
        "① 半剖：以对称中心线为界，一半画剖视、一半画视图；分界线必须是对称中心线（细点画线），不能画成粗实线。",
        "② 剖视侧的孔壁画粗实线、剖面线画到粗实线为止；视图侧的外形轮廓照常画。",
        "③ 视图半侧不画虚线 —— 内部形状已由剖视侧表达，再画虚线属重复。",
        "④ 标注时只注剖视侧的尺寸，对称尺寸一般注到中心线（不注整圆直径）。",
    ]
    F.lines(40, 470, notes, size=11, lh=23)
    F.text(40, 566, "⑤ 若对称中心线上有轮廓线（如键槽），不能用半剖，应改用局部剖。", size=11, anchor="start",
           color=RED)
    return F


