# 7. 局部剖视图（波浪线分界）
# ---------------------------------------------------------------------------
def fig_poushi_jubu() -> Figure:
    F = Figure(
        "FIG-POUSHI-JUBU",
        960,
        580,
        "局部剖视图：用波浪线分界剖开一个孔",
        "在带孔的平板上用波浪线作断裂边界，局部剖开中间部分显示内孔；剖到的孔壁画粗实线，"
        "未剖到的部分仍按外形画（孔画虚线）。",
    )
    fig_title(
        F,
        "图 7  局部剖视图（平板 120×50，竖直通孔 Ø20）",
        "局部剖用波浪线作断裂边界 —— 既显示局部内形，又保留大部分外形，不必画成整剖。",
    )

    # 平板主视图 + 通孔（孔的轴线用细点画线）
    F.rect(360, 210, 240, 100, cls="thick")
    F.line(480, 194, 480, 318, cls="center", color=MUTED)

    # 波浪线：局部剖的断裂边界（基准 y 从 250 过渡到 246）
    def ybase(x: float) -> float:
        return 250 - 4 * (x - 386) / 188

    W = F.wave_pts(386, 574, ybase, amp=3.4, period=16, step=2.0)
    wy = {round(x, 2): y for x, y in W}
    y460, y500 = wy[460.0], wy[500.0]

    # 剖切区域：左、右两块（中间让开孔）
    left = [(390, 210)] + [(x, y) for x, y in W if x <= 460.01] + [(460, 210)]
    right = [(500, 210)] + [(x, y) for x, y in W if x >= 499.99] + [(570, 210)]
    F.polyline(left, cls=None, close=True, fill="url(#hatch45)")
    F.polyline(right, cls=None, close=True, fill="url(#hatch45)")

    # 波浪线本身（细实线）
    F.polyline([(390, 210)] + W + [(570, 210)], cls="wave")

    # 剖到的孔壁：粗实线；未剖到的部分：虚线
    F.line(460, 210, 460, y460, cls="thick")
    F.line(500, 210, 500, y500, cls="thick")
    F.line(460, y460, 460, 310, cls="dash")
    F.line(500, y500, 500, 310, cls="dash")

    F.text(480, 190, "局部剖视图", size=12, weight="600")
    F.leader(560, 232, 640, 214, "波浪线（细实线，手画，不能与轮廓线重合）", color=RED, anchor="start")
    F.leader(500, 290, 630, 330, "未剖到的部分照外形画，孔画虚线", color=BLUE, anchor="start")

    # 尺寸
    F.dim_h(360, 600, 352, "120")
    F.dim_v(336, 210, 310, "50", ext_from=(360, 360))
    F.leader(470, 214, 300, 150, "Ø20 通孔", color=MUTED, anchor="end")

    notes = [
        "① 局部剖：用波浪线作断裂边界，只剖开需要表达内部结构的那一块，其余仍按外形画。",
        "② 波浪线必须画在零件的实体部分内，不能与轮廓线重合，不能画在孔、槽的空腔上，也不能是规则的正弦曲线。",
        "③ 波浪线遇到孔槽时应断开（孔槽处没有实体可以断裂）。",
        "④ 局部剖一般不加标注，位置由波浪线表达；同一视图上局部剖的数量不宜过多，避免支离破碎。",
    ]
    F.lines(40, 420, notes, size=11, lh=23)
    return F


