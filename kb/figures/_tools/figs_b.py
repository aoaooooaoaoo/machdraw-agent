# 5. 全剖视图
# ---------------------------------------------------------------------------
def fig_poushi_quan() -> Figure:
    F = Figure(
        "FIG-POUSHI-QUAN",
        1000,
        660,
        "全剖视图：带内孔圆筒的全剖",
        "左为外形视图（内孔画虚线），右为全剖视图（内孔轮廓变粗实线、空腔不画剖面线）；"
        "俯视图上用粗短画与箭头标出剖切位置线 A—A。",
    )
    fig_title(
        F,
        "图 5  全剖视图（圆筒：法兰 Ø80、筒体 Ø50、内孔 Ø28，高 60）",
        "用通过轴线的剖切平面把零件完全剖开，向后投射 —— 得到 A—A 全剖视图。",
    )

    # ---------- 左：外形视图 ----------
    F.path("M220,280 L250,280 L250,180 L350,180 L350,280 L380,280 L380,300 L220,300 Z", cls="thick")
    F.line(272, 180, 272, 300, cls="dash")  # 内孔不可见
    F.line(328, 180, 328, 300, cls="dash")
    F.line(300, 160, 300, 320, cls="center", color=MUTED)
    F.text(300, 148, "外形视图（内孔画虚线）", size=12, weight="600")

    # ---------- 俯视图（在主视图正下方，长对正） ----------
    F.circle(300, 410, 80, cls="thick")
    F.line(200, 410, 400, 410, cls="center", color=MUTED)
    F.line(300, 322, 300, 498, cls="center", color=MUTED)
    F.text(300, 528, "俯视图", size=12, weight="600")
    # 剖切位置线：粗短画 + 箭头（箭头指投射方向：由前向后 → 图上向上）
    F.line(220, 410, 186, 410, cls="cut")
    F.line(380, 410, 414, 410, cls="cut")
    F.line_arrow(186, 410, 186, 376, color=INK, cls="thick", both=False)
    F.line_arrow(414, 410, 414, 376, color=INK, cls="thick", both=False)
    F.text(178, 368, "A", size=12, weight="600", anchor="middle")
    F.text(422, 368, "A", size=12, weight="600", anchor="middle")

    # ---------- 右：全剖视图 ----------
    F.path("M640,280 L670,280 L670,180 L770,180 L770,280 L800,280 L800,300 L640,300 Z", cls="thick")
    F.hatch_rect(670, 180, 22, 100)  # 左筒壁
    F.hatch_rect(640, 280, 52, 20)  # 左法兰
    F.hatch_rect(748, 180, 22, 100)  # 右筒壁
    F.hatch_rect(748, 280, 52, 20)  # 右法兰
    F.line(692, 180, 692, 300, cls="thick")  # 内孔轮廓：剖开后变可见
    F.line(748, 180, 748, 300, cls="thick")
    F.line(720, 160, 720, 320, cls="center", color=MUTED)
    F.text(720, 148, "A—A 全剖视图", size=12, weight="600")

    # 引注
    F.leader(412, 410, 470, 430, "剖切位置线（粗短画 + 箭头）", color=RED, anchor="start")
    F.leader(778, 196, 856, 168, "剖面线：45° 细实线", color=MUTED, anchor="start")
    F.leader(330, 250, 416, 236, "内孔 Ø28", color=BLUE, anchor="start")

    notes = [
        "① 全剖：用剖切平面把零件完全剖开，移去前半部分后再投射；原被遮住的内部轮廓变成可见，画粗实线。",
        "② 剖切位置线用粗短画（本图 3 px）画在俯视图上，箭头指明投射方向，两端注相向的字母 A，并在剖视图上方注 A—A。",
        "③ 剖面线用 45° 细实线，间距均匀；同一零件在各剖视图中的方向、间距要一致。",
        "④ 空腔（内孔）里不画剖面线；剖面线一律画到粗实线为止，不能画进空腔或越过轮廓。",
    ]
    F.lines(40, 556, notes, size=11, lh=23)
    return F


